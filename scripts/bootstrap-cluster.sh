#!/usr/bin/env bash
# Installs cluster add-ons that the app chart depends on, then hands over to Argo CD.
# Run after `terraform apply` in infra/azure/envs/dev.
set -euo pipefail

TF_DIR=${TF_DIR:-infra/azure/envs/dev}
VALUES=${VALUES:-deploy/helm/sprocketry/values-azure.yaml}
# Pinned so every cluster gets the same add-ons. Bump deliberately and test.
ESO_VERSION=${ESO_VERSION:-2.12.0}
ENVOY_GATEWAY_VERSION=${ENVOY_GATEWAY_VERSION:-v1.9.2}
ARGOCD_CHART_VERSION=${ARGOCD_CHART_VERSION:-10.10.3}
ARGO_ROLLOUTS_CHART_VERSION=${ARGO_ROLLOUTS_CHART_VERSION:-2.43.7}
tf() { terraform -chdir="$TF_DIR" output -raw "$1"; }

RG=$(tf resource_group)
CLUSTER=$(tf aks_cluster_name)
CLIENT_IDS=$(terraform -chdir="$TF_DIR" output -json workload_identity_client_ids)
ESO_CLIENT_ID=$(jq -r '."external-secrets"' <<<"$CLIENT_IDS")

# Chart values come straight from Terraform outputs. An existing file is kept so local edits survive.
if [ ! -f "$VALUES" ]; then
  cat > "$VALUES" <<EOF
# Generated by scripts/bootstrap-cluster.sh from terraform outputs.
image:
  registry: $(tf acr_login_server)
  # Fallback only: CI pins each service to its commit SHA in values-image-tags.yaml.
  tag: latest
  pullPolicy: Always

azure:
  tenantId: "$(tf tenant_id)"
  keyVaultUrl: "$(tf key_vault_uri)"
  serviceBusNamespace: "$(tf servicebus_namespace)"
  appsClientId: "$(jq -r '.apps' <<<"$CLIENT_IDS")"

gateway:
  enabled: true

# Traces, metrics and logs into an in-cluster Grafana (make grafana).
observability:
  collector:
    enabled: true
  lgtm:
    enabled: true

# Canary releases (Argo Rollouts), judged on the in-cluster Prometheus, and runtime fault flags (flagd).
rollouts:
  enabled: true
flags:
  enabled: true
EOF
  echo "Wrote $VALUES"
fi

# Argo CD syncs from Git, so it must point at this repo and see the committed values file.
REPO_URL=${REPO_URL:-$(git remote get-url origin | sed -E 's#^git@([^:]+):#https://\1/#')}
if ! git ls-files --error-unmatch "$VALUES" >/dev/null 2>&1 || ! git diff --quiet HEAD -- "$VALUES"; then
  echo "WARNING: commit and push $VALUES to $REPO_URL, or Argo CD cannot sync." >&2
fi

# The cluster has no local accounts, so kubectl signs in through Entra ID using your az login.
az aks get-credentials -g "$RG" -n "$CLUSTER" --overwrite-existing
kubelogin convert-kubeconfig -l azurecli

# External Secrets Operator, running as the workload identity that can read Key Vault.
helm repo add external-secrets https://charts.external-secrets.io --force-update
helm upgrade --install external-secrets external-secrets/external-secrets \
  --version "$ESO_VERSION" -n external-secrets --create-namespace --wait \
  --set installCRDs=true \
  --set serviceAccount.name=external-secrets \
  --set "serviceAccount.annotations.azure\.workload\.identity/client-id=$ESO_CLIENT_ID" \
  --set "podLabels.azure\.workload\.identity/use=true"

# Envoy Gateway implements the Gateway API for public traffic.
helm upgrade --install envoy-gateway oci://docker.io/envoyproxy/gateway-helm \
  --version "$ENVOY_GATEWAY_VERSION" -n envoy-gateway-system --create-namespace --wait
kubectl apply -f deploy/gateway/gateway.yaml

# Argo Rollouts runs the services' canary releases (rollouts.enabled).
helm repo add argo https://argoproj.github.io/argo-helm --force-update
helm upgrade --install argo-rollouts argo/argo-rollouts \
  --version "$ARGO_ROLLOUTS_CHART_VERSION" -n argo-rollouts --create-namespace --wait

# Argo CD, then the app-of-apps that syncs everything else from Git.
helm upgrade --install argocd argo/argo-cd \
  --version "$ARGOCD_CHART_VERSION" -n argocd --create-namespace --wait
sed "s#repoURL: .*#repoURL: $REPO_URL#" deploy/argocd/sprocketry.yaml | kubectl apply -f -

echo "Bootstrap complete. Argo CD is syncing $REPO_URL into namespace 'sprocketry'."
echo "Waiting for the gateway's public address..."
kubectl wait gateway/public -n gateway-system --for=condition=Programmed --timeout=5m >/dev/null
echo "Storefront: http://$(kubectl get gateway/public -n gateway-system -o jsonpath='{.status.addresses[0].value}')"
